#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ЭТАП 1 — Проверка исходной геометрии 20×15 м (зал 13×15 + блок 7×15)
Чистая математика, без рисунков.
"""
W_EXT = 300   # наружная стена, мм
W_INT = 200   # внутренняя несущая/мокрая стена, мм

def check(name, W, D, pool_w=10000, pool_d=10000,
          side_min=2500, end_min=1500):
    """W,D — ЧИСТЫЕ внутренние габариты зала. Возвращает отчёт."""
    mx = (W - pool_w) / 2      # проходы слева/справа (по ширине)
    my = (D - pool_d) / 2      # проходы сверху/снизу (по глубине)
    lines = [
        f"  Чистый габарит зала: {W/1000:.2f} × {D/1000:.2f} м",
        f"  Проходы по оси X (пара сторон): {mx/1000:.2f} / {mx/1000:.2f} м",
        f"  Проходы по оси Y (пара сторон): {my/1000:.2f} / {my/1000:.2f} м",
    ]
    # боковые = 2500, торцевые = 1500 — проверяем оба варианта ориентации
    ok_a = mx >= end_min and my >= side_min   # боковые вдоль Y
    ok_b = mx >= side_min and my >= end_min   # боковые вдоль X
    lines.append(f"  Вариант А (боковые 2.50 по Y, торцевые 1.50 по X): "
                 f"{'OK' if ok_a else 'НАРУШЕНИЕ'}")
    if not ok_a:
        if mx < end_min:
            lines.append(f"    ✗ торцевой проход {mx/1000:.2f} < 1.50 м")
        if my < side_min:
            lines.append(f"    ✗ боковой проход {my/1000:.2f} < 2.50 м")
    lines.append(f"  Вариант Б (боковые 2.50 по X, торцевые 1.50 по Y): "
                 f"{'OK' if ok_b else 'НАРУШЕНИЕ'}")
    if not ok_b:
        if mx < side_min:
            lines.append(f"    ✗ боковой проход {mx/1000:.2f} < 2.50 м")
        if my < end_min:
            lines.append(f"    ✗ торцевой проход {my/1000:.2f} < 1.50 м")
    print(f"■ {name}")
    print("\n".join(lines))
    print()
    return ok_a or ok_b

print("="*72)
print("ПРОВЕРКА 1. Исходная геометрия ТЗ: здание 20×15, зал 13×15 (по осям)")
print("="*72)
# зал 13.00 м по осям: минус divider 200 и наружная 300
hall_clear_w = 13000 - W_INT - W_EXT          # 12500
hall_clear_d = 15000 - W_EXT - W_EXT          # 14400
check("Зал 13.0 × 15.0 (осевые), стены 300/200", hall_clear_w, hall_clear_d)

print("="*72)
print("ПРОВЕРКА 2. Предельный случай: зал во ВСЮ глубину здания 15 м")
print("="*72)
check("Зал 13.5 × 15.0", 13000, 15000 - 600)

print("Вывод: при глубине здания 15.0 м максимально возможная чистая")
print("глубина зала = 14.40 м < 15.00 м = 10.00 + 2.50 + 2.50.")
print("=> Боковые проходы 2.50 м с ДВУХ сторон в габарите 15.0 м")
print("   НЕВЫПОЛНИМЫ НИ ПРИ КАКОЙ планировке (не хватает 0.60 м).")
print()
print("="*72)
print("ПРОВЕРКА 3. Альтернатива: боковые 2.50 вдоль ШИРИНЫ здания (20 м)")
print("="*72)
# тогда зал нужен шириной >= 15.0 чистыми => axis 15+0.2+0.3=15.5
# сервисный блок = 20 - 15.5 = 4.5 по осям => чистая ширина 4.5-0.5=4.0
prog = [("тамбур",4),("холл",8),("раздевалка",18),("с/у",4),("душевые",9),
        ("русская парная",9),("финская сауна",6),("хамам",9)]
need = sum(a for _,a in prog)
strip = (4500-500)/1000 * (15000-600)/1000
print(f"  Зал по осям: 15.50 м → сервисный блок: 4.50 м (чистыми "
      f"{4.0:.2f} × 14.40 = {4.0*14.4:.1f} м²)")
print(f"  Минимальная нетто-программа банного блока (без коридоров):")
for n,a in prog: print(f"    {n:<18} {a:>4} м²")
print(f"    {'ИТОГО':<18} {need:>4} м²  + коридоры ≥ 12 м² = {need+12} м²")
print(f"  Доступно в блоке: {strip:.1f} м² → дефицит ≈ {need+12-strip:.0f} м²")
print("=> Вариант Б тоже НЕРАБОЧИЙ: банный блок не помещается в 4.5 м.")
print()
print("="*72)
print("БЮДЖЕТ ПЛОЩАДЕЙ (минимум для согласованной схемы)")
print("="*72)
print("  Бассейновый зал (10×10 + 2.5/2.5 + 1.5/1.5 + стены): "
      "13.5×15.6 осев. ≈ 211 м²")
print("  Сервисно-банный блок (8 помещений + проходы):          ≈ 95 м²")
print("  Зона отдыха (открытая, 25–30 м²):                      ≈ 29 м²")
print("  Техблок (насосная 10 + инженерная 12 + стены):          ≈ 27 м²")
print("  ИТОГО: ≈ 356–362 м² против заявленных 300 м²")
print("  Дефицит: ≈ +18% площади.")
